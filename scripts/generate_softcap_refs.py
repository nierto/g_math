#!/usr/bin/env python3
"""References for fused::softcap* and fused::softcapped_swiglu* (tests/softcap_validation.rs).

softcap(x, c) = c tanh(x / c); swiglu(g, u) = gc tanh(g / gc) sigmoid(g) uc tanh(u / uc).
Values by mpmath at 150 digits, written with 150 significant digits; the test
parses them at the build's format (the exact decimal parser rounds once to
nearest), so each expected word is the correctly rounded result. Inputs are
multiples of 2^-8 (2^-16 for the wide forms, given as integers k: x = k / 65536)
with every |input| and |result| at most 120, so they are exact and in range at
every format the suite runs. No floats: every input is built from integers.
"""
import os
from fractions import Fraction as Fr
from mpmath import mp, mpf, tanh, exp, nstr

mp.dps = 170


class Rng:
    def __init__(self, s):
        self.s = s

    def next(self):
        s = self.s
        s ^= s >> 12
        s ^= (s << 25) & ((1 << 64) - 1)
        s ^= s >> 27
        self.s = s
        return (s * 0x2545F4914F6CDD1D) & ((1 << 64) - 1)


def dec(fr):
    """Exact decimal string of a dyadic fraction."""
    n, d = fr.numerator, fr.denominator
    sign = "-" if n < 0 else ""
    n = abs(n)
    ip, rem = divmod(n, d)
    if rem == 0:
        return f"{sign}{ip}"
    k = d.bit_length() - 1
    assert d == 1 << k
    frac = rem * 5**k
    return f"{sign}{ip}.{frac:0{k}d}".rstrip("0")


def val(s):
    return nstr(s, 150, strip_zeros=False)


def softcap(x, c):
    x, c = mpf(x.numerator) / x.denominator, mpf(c.numerator) / c.denominator
    return c * tanh(x / c)


def sigmoid(g):
    return 1 / (1 + exp(-g))


def swiglu(g, u, gc, uc):
    g, u = mpf(g.numerator) / g.denominator, mpf(u.numerator) / u.denominator
    gc, uc = mpf(gc.numerator) / gc.denominator, mpf(uc.numerator) / uc.denominator
    return gc * tanh(g / gc) * sigmoid(g) * uc * tanh(u / uc)


def grid(rng, bits, lim):
    """A random multiple of 2^-bits in [-lim, lim], mostly small."""
    r = rng.next()
    scale = [1, 4, 16, lim][r % 4]
    k = (r >> 8) % (2 * scale * (1 << bits) + 1) - scale * (1 << bits)
    return Fr(k, 1 << bits)


def main():
    rng = Rng(0x50F7CA9)
    soft, soft_w, swi, swi_w = [], [], [], []
    caps = [Fr(30), Fr(4), Fr(25), Fr(-7), Fr(3, 4), Fr(100)]
    edges = [Fr(0), Fr(1, 256), Fr(-1, 256), Fr(120), Fr(-120), Fr(255, 256), Fr(-3, 2)]
    for c in caps:
        for x in edges + [grid(rng, 8, 120) for _ in range(20)]:
            soft.append((dec(x), dec(c), val(softcap(x, c))))
        for i in range(10):
            lim = 120 if i < 6 else 1
            k = (rng.next() >> 8) % (2 * lim * 65536 + 1) - lim * 65536
            soft_w.append((k, dec(c), val(softcap(Fr(k, 65536), c))))
    # the last pair keeps caps, inputs and results within +-1.5: it fits the narrowest split (Q2.30)
    for gc, uc in [(Fr(4), Fr(25)), (Fr(-4), Fr(25)), (Fr(1, 2), Fr(3)), (Fr(8), Fr(12)), (Fr(1, 2), Fr(3, 2))]:
        bound = abs(gc * uc)
        assert bound <= 120
        lim = 120 if bound > 1 else 1
        if lim == 120:
            pairs = [(Fr(0), Fr(5)), (Fr(5), Fr(0)), (Fr(120), Fr(120)), (Fr(-120), Fr(120)), (Fr(-120), Fr(-120)), (Fr(1, 256), Fr(-1, 256))]
        else:
            pairs = [(Fr(0), Fr(1)), (Fr(1), Fr(0)), (Fr(3, 2), Fr(3, 2)), (Fr(-3, 2), Fr(3, 2)), (Fr(-3, 2), Fr(-3, 2)), (Fr(1, 256), Fr(-1, 256))]
        pairs += [(grid(rng, 8, lim), grid(rng, 8, lim)) for _ in range(34)]
        for g, u in pairs:
            swi.append((dec(g), dec(u), dec(gc), dec(uc), val(swiglu(g, u, gc, uc))))
        wl = 64 if lim == 120 else 1
        for _ in range(15):
            kg = (rng.next() >> 8) % (2 * wl * 65536 + 1) - wl * 65536
            ku = (rng.next() >> 8) % (2 * wl * 65536 + 1) - wl * 65536
            swi_w.append((kg, ku, dec(gc), dec(uc), val(swiglu(Fr(kg, 65536), Fr(ku, 65536), gc, uc))))
    # x * sigmoid(g) on wide inputs (k / 65536), |x| <= 120 and small pairs for the narrow splits
    sig_w = []
    for i in range(80):
        lim = 120 if i < 60 else 1
        kx = (rng.next() >> 8) % (2 * lim * 65536 + 1) - lim * 65536
        glim = 40 if i < 60 else 1  # small gates too: they fit the narrowest wide word (Q4.60 at Q2.30)
        kg = (rng.next() >> 8) % (2 * glim * 65536 + 1) - glim * 65536
        x, g = mpf(kx) / 65536, mpf(kg) / 65536
        sig_w.append((kx, kg, val(x * sigmoid(g))))
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "data", "softcap_refs.rs")
    q = lambda s: '"' + s + '"'
    with open(out, "w") as f:
        f.write("// Generated by scripts/generate_softcap_refs.py (mpmath, 170-digit working precision). Do not edit.\n\n")
        f.write("/// (x, cap, cap tanh(x / cap))\npub const SOFTCAP: &[(&str, &str, &str)] = &[\n")
        for x, c, y in soft:
            f.write(f"    ({q(x)}, {q(c)}, {q(y)}),\n")
        f.write("];\n\n/// (k, cap, value) with x = k / 65536 (wide input)\npub const SOFTCAP_WIDE: &[(i64, &str, &str)] = &[\n")
        for k, c, y in soft_w:
            f.write(f"    ({k}, {q(c)}, {q(y)}),\n")
        f.write("];\n\n/// (gate, up, gate cap, up cap, value)\npub const SWIGLU: &[(&str, &str, &str, &str, &str)] = &[\n")
        for g, u, gc, uc, y in swi:
            f.write(f"    ({q(g)}, {q(u)}, {q(gc)}, {q(uc)}, {q(y)}),\n")
        f.write("];\n\n/// (kg, ku, gate cap, up cap, value) with gate = kg / 65536, up = ku / 65536 (wide inputs)\npub const SWIGLU_WIDE: &[(i64, i64, &str, &str, &str)] = &[\n")
        for kg, ku, gc, uc, y in swi_w:
            f.write(f"    ({kg}, {ku}, {q(gc)}, {q(uc)}, {q(y)}),\n")
        f.write("];\n\n/// (kx, kg, x * sigmoid(g)) with x = kx / 65536, g = kg / 65536 (wide inputs)\npub const SIGMUL_WIDE: &[(i64, i64, &str)] = &[\n")
        for kx, kg, y in sig_w:
            f.write(f"    ({kx}, {kg}, {q(y)}),\n")
        f.write("];\n")
    print(f"{len(soft)} softcap, {len(soft_w)} wide softcap, {len(swi)} swiglu, {len(swi_w)} wide swiglu; wrote {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
