#!/usr/bin/env python3
"""References for walsh_hadamard_in_place (tests/hadamard_validation.rs).

H x with H[r][c] = (-1)^popcount(r & c) by the matrix definition, once with
Python integers and once with mpmath (200 digits), asserted equal; for
n = 4^j also floor(H x / sqrt(n)) by mpmath's real sqrt against the integer
shift by log2(n) / 2 (the normalisation a caller folds into one rounding).
Cases: every length 1..1024 by powers of two, values near the i32 / i64
limits (the checked path and refusals), 120-bit values for I256. No floats.
"""
import os
from mpmath import mp, mpf, sqrt, floor as mfloor

mp.dps = 200


class Rng:
    def __init__(self, s):
        self.s = s

    def next(self):
        s = self.s
        s ^= s >> 12
        s ^= (s << 25) & ((1 << 64) - 1)
        s ^= s >> 27
        self.s = s
        return (s * 0x2545F4914F6CDD1D) & ((1 << 64) - 1)


def transform(x):
    n = len(x)
    out = []
    for r in range(n):
        s = 0
        sm = mpf(0)
        for c in range(n):
            neg = bin(r & c).count("1") % 2
            s += -x[c] if neg else x[c]
            sm += -mpf(x[c]) if neg else mpf(x[c])
        assert int(sm) == s
        out.append(s)
    k = n.bit_length() - 1
    if k % 2 == 0:
        for v in out:
            assert int(mfloor(mpf(v) / sqrt(n))) == v >> (k // 2)
    return out


def main():
    rng = Rng(0x4ADA3A4D)
    cases = []
    for k in range(11):
        n = 1 << k
        for bits in (8, 31, 52):
            x = [(rng.next() % (1 << bits)) - (1 << (bits - 1)) for _ in range(n)]
            cases.append(("i64", x, transform(x)))
    # i32: fits after the transform / does not (an error, input unchanged)
    cases.append(("i32", [(1 << 30) - 1, (1 << 30) - 1], transform([(1 << 30) - 1, (1 << 30) - 1])))
    cases.append(("i32", [(1 << 31) - 1, 1], None))
    cases.append(("i32", [-(1 << 31), 0, 0, 0], transform([-(1 << 31), 0, 0, 0])))
    cases.append(("i32", [-(1 << 31), 1, 0, 0], None))
    cases.append(("i32", [(1 << 27) - 5] * 16, transform([(1 << 27) - 5] * 16)))
    # wide words: 120-bit values at n = 64
    x = [(rng.next() << 56 | rng.next()) % (1 << 120) - (1 << 119) for _ in range(64)]
    cases.append(("i256", x, transform(x)))
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "data", "hadamard_refs.rs")
    with open(out, "w") as f:
        f.write("// Generated by scripts/generate_hadamard_refs.py (integers, confirmed by mpmath). Do not edit.\n\n")
        f.write("/// (word, input, H x or None when it leaves the word); values as decimal strings\n")
        f.write("pub const CASES: &[(&str, &[&str], Option<&[&str]>)] = &[\n")
        for word, x, y in cases:
            xs = ", ".join(f'"{v}"' for v in x)
            ys = "None" if y is None else "Some(&[" + ", ".join(f'"{v}"' for v in y) + "])"
            f.write(f'    ("{word}", &[{xs}], {ys}),\n')
        f.write("];\n")
    print(f"{len(cases)} cases; wrote {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
